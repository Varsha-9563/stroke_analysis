"""
CSV data logger: every glove recording is appended to CSV files, per patient.

backend/data/
├── all_sessions.csv                one row per recording, everyone (patients + healthy volunteers)
├── healthy_reference.csv           one row per recording of HEALTHY volunteers only
│                                   (this is the "normal hand" the patients are compared with)
└── patients/
    ├── P0003_sessions.csv          one row per recording for patient 3
    └── P0003_readings.csv          every raw reading (50 per second) of every recording

"day" = number of days since the patient's FIRST recording (day 0), so recovery
can be followed over days, weeks and months.
"group" = patient or healthy.   "data_source" = glove (real glove), simulator
(hardware/glove_simulator.py) or synthetic (generated by seed_data.py).

These files hold patient data: they are ignored by git (see .gitignore).
"""
import csv
import threading
from datetime import datetime
from pathlib import Path

import numpy as np

from analysis import FINGERS, N, adc_to_angle

DATA_DIR = Path(__file__).resolve().parent / "data"
PATIENT_DIR = DATA_DIR / "patients"
ALL_SESSIONS = DATA_DIR / "all_sessions.csv"
HEALTHY_REFERENCE = DATA_DIR / "healthy_reference.csv"

FINGER_NAMES = ["pinky" if f == "little" else f for f in FINGERS]   # index, middle, ring, pinky

SESSION_COLUMNS = (
    ["patient_id", "patient_name", "group", "data_source", "session_id", "recorded_at", "day",
     "duration_s", "readings", "recovery_score", "change_from_first", "change_from_previous",
     "pct_of_healthy"]
    + [f"{f}_rom_deg" for f in FINGER_NAMES]
    + [f"{f}_bends" for f in FINGER_NAMES]
    + [f"{f}_status" for f in FINGER_NAMES]
    + ["calibrated"]
)
READING_COLUMNS = (["patient_id", "session_id", "recorded_at", "day", "t_ms"]
                   + [f"{f}_raw" for f in FINGER_NAMES]
                   + [f"{f}_angle_deg" for f in FINGER_NAMES])

_lock = threading.Lock()


def patient_code(patient_id):
    return f"P{patient_id:04d}"


def sessions_file(patient_id):
    return PATIENT_DIR / f"{patient_code(patient_id)}_sessions.csv"


def readings_file(patient_id):
    return PATIENT_DIR / f"{patient_code(patient_id)}_readings.csv"


def _append(path: Path, columns, rows):
    path.parent.mkdir(parents=True, exist_ok=True)
    new = not path.exists()
    with open(path, "a", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=columns)
        if new:
            w.writeheader()
        w.writerows(rows)


def count_bends(angle, fs=50):
    """Count full bends (open -> bent -> open) of one finger.
    Smooths out tremor first, then counts a bend only when the finger goes
    above 65% of its range after having been below 35% (hysteresis)."""
    a = np.asarray(angle, dtype=float)
    if len(a) < fs:
        return 0
    k = max(3, int(0.3 * fs))
    a = np.convolve(a, np.ones(k) / k, mode="valid")
    lo, hi = np.percentile(a, 5), np.percentile(a, 95)
    if hi - lo < 5:                 # finger barely moved
        return 0
    low, high = lo + 0.35 * (hi - lo), lo + 0.65 * (hi - lo)
    bends, ready = 0, a[0] < high
    for v in a:
        if ready and v > high:
            bends += 1
            ready = False
        elif not ready and v < low:
            ready = True
    return bends


def log_session(patient, session, samples, result, calibration=None):
    """Append one recording to the CSV files.

    patient  : database Patient (its .sessions must already include `session`)
    session  : the saved GloveSession
    samples  : raw readings [[t_ms, index, middle, ring, pinky], ...]
    result   : output of analyze_session()
    """
    sessions = patient.sessions
    first = sessions[0]
    previous = sessions[-2] if len(sessions) >= 2 else None
    day = (session.recorded_at.date() - first.recorded_at.date()).days

    arr = np.asarray(samples, dtype=float)
    duration = (arr[-1, 0] - arr[0, 0]) / 1000 if len(arr) > 1 else 0
    angles = adc_to_angle(arr[:, 1:N + 1], calibration)

    from healthy import pct_of_healthy   # local import: healthy.py reads the CSV this module writes
    group = patient.group or "patient"
    row = {
        "patient_id": patient_code(patient.id),
        "patient_name": patient.user.name,
        "group": group,
        "data_source": session.data_source or "glove",
        "session_id": session.id,
        "recorded_at": session.recorded_at.isoformat(timespec="seconds"),
        "day": day,
        "duration_s": round(duration, 1),
        "readings": len(samples),
        "recovery_score": result["recovery_score"],
        "change_from_first": round(result["recovery_score"] - first.recovery_score, 1),
        "change_from_previous": round(result["recovery_score"] - previous.recovery_score, 1) if previous else "",
        "calibrated": bool(calibration),
        "pct_of_healthy": "",
    }
    for f, name in zip(FINGERS, FINGER_NAMES):
        row[f"{name}_rom_deg"] = result["range_of_motion"][f]
        row[f"{name}_bends"] = count_bends(angles[:, FINGERS.index(f)])
        row[f"{name}_status"] = result["finger_status"][f]
    if group == "patient":
        pct = pct_of_healthy(result["range_of_motion"])
        row["pct_of_healthy"] = pct["overall"] if pct else ""

    stamp = session.recorded_at.isoformat(timespec="seconds")
    reading_rows = []
    for s, a in zip(samples, angles):
        r = {"patient_id": patient_code(patient.id), "session_id": session.id,
             "recorded_at": stamp, "day": day, "t_ms": int(s[0])}
        for i, name in enumerate(FINGER_NAMES):
            r[f"{name}_raw"] = int(s[i + 1])
            r[f"{name}_angle_deg"] = round(float(np.clip(a[i], 0, 120)), 1)
        reading_rows.append(r)

    with _lock:
        _append(sessions_file(patient.id), SESSION_COLUMNS, [row])
        _append(ALL_SESSIONS, SESSION_COLUMNS, [row])
        if group == "healthy":
            _append(HEALTHY_REFERENCE, SESSION_COLUMNS, [row])
        _append(readings_file(patient.id), READING_COLUMNS, reading_rows)
    return row


def reset_all():
    """Delete all CSV logs (used by seed_data.py when it rebuilds the demo data)."""
    with _lock:
        for f in (ALL_SESSIONS, HEALTHY_REFERENCE):
            if f.exists():
                f.unlink()
        if PATIENT_DIR.exists():
            for f in PATIENT_DIR.glob("*.csv"):
                f.unlink()


def file_info(patient_id):
    out = {}
    for kind, path in (("sessions", sessions_file(patient_id)), ("readings", readings_file(patient_id))):
        if path.exists():
            with open(path, encoding="utf-8") as fh:
                rows = sum(1 for _ in fh) - 1
            out[kind] = {"file": path.name, "rows": rows, "updated": datetime.fromtimestamp(path.stat().st_mtime).isoformat(timespec="seconds")}
        else:
            out[kind] = {"file": path.name, "rows": 0, "updated": None}
    return out
